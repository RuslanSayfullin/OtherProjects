# Дан целочисленный массив фиксированной длины `arr`. Необходимо продублировать каждое вхождение нуля, сдвинув остальные элементы вправо.
# Обратите внимание, что элементы, выходящие за пределы исходной длины массива, не записываются. 
# Выполните эти изменения непосредственно в исходном массиве; ничего возвращать не нужно.
from collections import deque

class Solution:
    def duplicateZeros(self, arr: list[int]) -> None:
        n = len(arr)
        zeros = 0
        i = 0

        # Первый проход: считаем, сколько нулей войдёт в массив
        while i + zeros < n:
            if arr[i] == 0:
                zeros += 1
            i += 1

        # i теперь указывает на первый элемент, который не войдёт (или n, если всё вошло)
        # zeros — количество нулей, которые будут продублированы

        # Второй проход: заполняем массив с конца
        j = n - 1
        i -= 1  # начинаем с последнего элемента, который «войдёт»

        # Если последний учтённый элемент был нулём и он «вылезает» за границу,
        # то его нужно продублировать только один раз.
        if i + zeros == n:
            # Это значит, что последний ноль выходит за границу — ставим один ноль
            arr[j] = 0
            j -= 1
            i -= 1

        while j >= 0 and i >= 0:
            if arr[i] == 0:
                arr[j] = 0
                j -= 1
                if j >= 0:  # если есть место, дублируем
                    arr[j] = 0
                    j -= 1
            else:
                arr[j] = arr[i]
                j -= 1
            i -= 1

example = Solution()

arr = [1,0,2,3,0,4,5,0]
example.duplicateZeros(arr)
